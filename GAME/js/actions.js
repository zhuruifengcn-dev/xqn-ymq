/* ---------------- 辅助 ---------------- */
function ok(g, title, text, changes, npcNote) {
  return { 标题: title, 叙事: text, 数值变化: changes, 选项: [{ 名: '继续', 效果: null, 后续: '' }], NPC备注: npcNote || '' };
}
function fail(g, title, text) {
  return { 标题: title + ' · 未成', 叙事: text, 数值变化: ['无变化'], 选项: [{ 名: '继续', 效果: null, 后续: '' }] };
}
